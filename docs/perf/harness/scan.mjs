import { writeFile } from 'node:fs/promises';
import { serve, launch, sleep, START } from './cdp.mjs';
const [dist, level, lang = 'zh'] = process.argv.slice(2);
const srv = await serve(dist); const c = await launch({ width: 844, height: 390 });
await c.send('Emulation.setDeviceMetricsOverride', { width: 844, height: 390, deviceScaleFactor: 2, mobile: true });
await c.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
await c.send('Page.addScriptToEvaluateOnNewDocument', { source: `try{localStorage.setItem('wd.levels','["plaza","harbor","works"]');localStorage.setItem('wd.lang','${lang}');}catch{}` });
await c.send('Page.navigate', { url: `http://127.0.0.1:${srv.port}/?test&dev&level=${level}&style=graffiti` });
await c.waitFor(`window.T && document.querySelector('.start-btn') && window.__WD && __WD.state === 'TITLE'`);
await c.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 5, y: 5 }] });
await c.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
const SCAN = `(() => { const re=/(?<![A-Za-z0-9{<&\\/'’_-])(WASD|Space|Shift|Tab|Esc|Alt|Enter|[EQRFCZXGVTBYH])(?![A-Za-z0-9}>;'’_-])|[Cc]lick|[Mm]ouse|鼠标|点击|[左右]键|键盘/; const out=[]; const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT); let n; while((n=w.nextNode())){ const el=n.parentElement; if(!el||!el.offsetParent&&getComputedStyle(el).position!=='fixed') continue; const cs=getComputedStyle(el); if(cs.visibility==='hidden'||cs.display==='none'||+cs.opacity===0) continue; const r=el.getBoundingClientRect(); if(r.width<2||r.height<2) continue; const t=n.textContent.trim(); if(t&&re.test(t.replace(/〔[^〕]+〕|\\[[^\\]]+\\]/g,''))) out.push((el.className||el.tagName)+': '+t.slice(0,90)); } return out; })()`;
const res = {};
res.title = await c.ev(SCAN);
console.error(JSON.stringify(await c.ev(START)));
await sleep(400);
await c.ev(`document.querySelector('.objective-toggle')?.click(); 1`);
await c.ev(`__WD.app.ui.toast(__WD.app.ui.constructor ? 'Hold Q to purify the eye' : '', 'info', true); 1`).catch(() => {});
await sleep(300);
res.hud = await c.ev(SCAN);
res.hudText = await c.ev(`[document.querySelector('.obj-hint')?.textContent, ...[...document.querySelectorAll('.toast')].map(e=>e.textContent)]`);
await c.ev(`window.dispatchEvent(new KeyboardEvent('keydown',{code:'Escape'})); 1`);
await sleep(900);
res.pause = await c.ev(SCAN);
const { data } = await c.send('Page.captureScreenshot', { format: 'png' });
await writeFile(`./scan-${level}-pause.png`, Buffer.from(data, 'base64'));
console.log(JSON.stringify(res, null, 1)); console.log('errors', c.errors.slice(0, 3));
c.close(); srv.close();
